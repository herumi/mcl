# generate src/msm_avx_para.h : the constants of the curves for the AVX-512 IFMA MSM (src/msm_avx.cpp)
# Fp is represented by N = ceil(MCL_FP_BIT / 52) limbs of 52 bits in the Montgomery form with R = 2^(52 N).
# The table has the curves whose p satisfies bits(p) <= 52 N - 2 (one conditional subtraction in vmul).
import sys
import random
from montgomery import Montgomery
from primetbl import curveTbl
from gen_glv import glvCurves, makeParam, sqrtMod

# rw of the GLV method verified on a point of G1 by gen_glv.py (mulLambda of msm_avx.cpp must use the same root)
glvRw = {e[0]: makeParam(*e).rw for e in glvCurves}

W = 52

def toArray(x, n, w):
  mask = (1 << w) - 1
  a = []
  for i in range(n):
    a.append(x & mask)
    x >>= w
  assert x == 0
  return a

def hexList(a):
  return ', '.join(map(hex, a))

# the two primitive cube roots of unity mod p (rw^2 + rw + 1 = 0) : (-1 +- sqrt(-3)) / 2
def cubeRootsOfUnity(p):
  s = sqrtMod(-3, p) # Tonelli-Shanks (p = 1 mod 4 for Grumpkin)
  assert s is not None and (s * s + 3) % p == 0
  rw = (-(1 + s) * pow(2, -1, p)) % p
  roots = [rw, rw * rw % p]
  for rw in roots:
    assert (rw * rw + rw + 1) % p == 0
  return roots

class Para:
  def __init__(self, cv, N):
    p = cv.p
    self.cv = cv
    self.N = N
    self.pN = (p.bit_length() + 63) // 64 # the number of 64-bit limbs of Fp (Fp::getOp().N)
    assert p.bit_length() <= W * N - 2, cv.name
    mont = Montgomery(p, W)
    assert mont.N <= N
    mont.N = N
    mont.R = pow(2, W * N, p)
    mont.R2 = mont.R * mont.R % p
    self.mont = mont
    R52 = mont.R
    R64 = pow(2, 64 * self.pN, p)
    s = W * N - 64 * self.pN # R52 = R64 * 2^s
    assert s > 0
    toMont = lambda x: x * R52 % p
    self.rp = mont.rp
    self.ap = toArray(p, N, W)
    self.R = toArray(R52, N, W)
    self.R2 = toArray(mont.R2, N, W)
    self.rawOne = toArray(1, N, W)
    self.m64to52 = toArray(toMont(pow(2, s, p)), N, W)
    self.m52to64 = toArray(toMont(pow(2, -s, p)), N, W)
    self.m52to64s = toArray(pow(2, -s, p) * R64 % p, self.pN, 64) # the Montgomery form of Fp
    self.invR52 = toArray(pow(R52, -1, p), self.pN, 64) # for Fp not in the Montgomery form (secp256k1)
    # the root used by the GLV method (verified on a point by gen_glv.py) ; the other root gives a different lattice
    rw = glvRw[cv.name]
    assert rw in cubeRootsOfUnity(p), cv.name
    self.rw = toArray(toMont(rw), N, W)
    assert cv.b != 0, cv.name
    self.b3 = toArray(toMont(3 * cv.b % p), N, W) # b may be negative (Grumpkin : b = -17)
    self.p = toArray(p, self.pN, 64)
    # verify the conversions : x R64 (Fp) -> x R52 (FpM) -> x R64
    rng = random.Random(1)
    for _ in range(100):
      x = rng.randrange(p)
      a = x * R64 % p
      m = a * pow(2, s, p) * R52 % p * pow(R52, -1, p) % p # FpM::mul(a, m64to52)
      assert m == x * R52 % p
      b = m * pow(2, -s, p) * R52 % p * pow(R52, -1, p) % p # FpM::mul(m, m52to64)
      assert b == a
      c = m * (pow(2, -s, p) * R64 % p) * pow(R64, -1, p) % p # Fp::mul(m, m52to64s)
      assert c == a
      # Fp not in the Montgomery form (secp256k1) : x -> x R52 by FpM::mul(x, R2), x R52 -> x by FpM::mul(x, 1) and by Fp::mul(x, invR52)
      m = x * mont.R2 % p * pow(R52, -1, p) % p
      assert m == x * R52 % p
      assert m * 1 * pow(R52, -1, p) % p == x
      assert m * pow(R52, -1, p) % p == x
    assert (self.rp * (p & ((1 << W) - 1)) + 1) % (1 << W) == 0

  def put(self):
    cv = self.cv
    N = self.N
    pad = lambda a, n: a + [0] * (n - len(a))
    print(f'\t{{ // {cv.name}')
    print(f'\t\t{cv.c}, {self.pN}, {cv.b},')
    print(f'\t\t{{ {hexList(pad(self.p, 6))} }}, // p')
    print(f'\t\t{hex(self.rp)}, // rp')
    print(f'\t\t{{ {hexList(self.ap)} }}, // ap')
    print(f'\t\t{{ {hexList(self.R)} }}, // R')
    print(f'\t\t{{ {hexList(self.R2)} }}, // R2')
    print(f'\t\t{{ {hexList(self.rawOne)} }}, // rawOne')
    print(f'\t\t{{ {hexList(self.m64to52)} }}, // m64to52')
    print(f'\t\t{{ {hexList(self.m52to64)} }}, // m52to64')
    print(f'\t\t{{ {hexList(pad(self.m52to64s, 6))} }}, // m52to64s')
    print(f'\t\t{{ {hexList(pad(self.invR52, 6))} }}, // invR52')
    print(f'\t\t{{ {hexList(self.rw)} }}, // rw')
    print(f'\t\t{{ {hexList(self.b3)} }}, // b3')
    print('\t},')

def putTable(fpBit, N):
  print(f'#if MCL_FP_BIT == {fpBit}')
  print(f'static const size_t MSM_N = {N}; // the number of 52-bit limbs')
  print('static const MsmCurvePara g_msmCurveTbl[] = {')
  for name in ['BN254', 'BN-SNARK', 'BLS12-381', 'BLS12-377', 'secp256k1', 'Grumpkin']:
    cv = curveTbl[name]
    if cv.p.bit_length() > W * N - 2:
      continue
    Para(cv, N).put()
  print('};')
  print('#endif')

def main():
  print('// generated by src/gen_msm_para.py')
  print('''/*
	the constants of the curves for the AVX-512 IFMA MSM (src/msm_avx.cpp)
	Fp is represented by MSM_N limbs of 52 bits in the Montgomery form with R52 = 2^(52 MSM_N) (FpM),
	while the Montgomery form of Fp uses R64 = 2^(64 pN). The curves with bits(p) <= 52 MSM_N - 2 are listed.
	initMsm selects the entry by p and expands the constants to the SIMD lanes.
*/
struct MsmCurvePara {
	int curveType; // MCL_BN254, MCL_BLS12_381, ...
	size_t pN; // the number of 64-bit limbs of p (= Fp::getOp().N)
	int b; // y^2 = x^3 + b (EcMT::specialB_ : Plus1 / Plus4 / GenericB ; may be negative)
	uint64_t p[6]; // p in 64-bit limbs
	uint64_t rp; // -p^-1 mod 2^52
	uint64_t ap[8]; // p in 52-bit limbs
	uint64_t R[8]; // R52 mod p (one)
	uint64_t R2[8]; // R52^2 mod p
	uint64_t rawOne[8]; // 1
	uint64_t m64to52[8]; // R52 (R52 / R64) mod p : Fp -> FpM by FpM::mul
	uint64_t m52to64[8]; // R52 (R64 / R52) mod p : FpM -> Fp by FpM::mul
	uint64_t m52to64s[6]; // R64 (R64 / R52) mod p in 64-bit limbs : FpM -> Fp by Fp::mul
	uint64_t invR52[6]; // R52^-1 mod p in 64-bit limbs : FpM -> Fp by Fp::mul if Fp is not in the Montgomery form (secp256k1)
	uint64_t rw[8]; // a primitive cube root of unity (for mulLambda)
	uint64_t b3[8]; // 3 b of y^2 = x^3 + b
};''')
  putTable(256, 5)
  putTable(384, 8)

if __name__ == '__main__':
  main()
