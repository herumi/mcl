# p-fixed functions of BLS12-381 (curve type 5) generated by common.gen_fixed
# (src/gen.py): the same ABI as the Xbyak functions (no p argument), so they
# are registered to the A_ slots of Op (see setLLVMFixedCode in fp.cpp).
# (slot of Op, suffix of the function name, C argument list)
# The function name is the prefix ('mcl_c5_fp_', 'mcl_c5_fr_') with the last
# '_' replaced by the suffix: 'Dbl_mod' -> mcl_c5_fpDbl_mod, '2_add' -> mcl_c5_fp2_add.
void2u = 'Unit*, const Unit*'
c5_fp_tbl = [
	('fp_addA_', '_add', void3u),
	('fp_subA_', '_sub', void3u),
	('fp_negA_', '_neg', void2u),
	('fp_mul2A_', '_mul2', void2u),
	('fp_mulA_', '_mul', void3u),
	('fp_sqrA_', '_sqr', void2u),
	('fpDbl_modA_', 'Dbl_mod', void2u),
]
# only for Fp (hasFp2 of gen_fixed)
c5_fpDbl_tbl = [
	('fpDbl_addA_', 'Dbl_add', void3u),
	('fpDbl_subA_', 'Dbl_sub', void3u),
]
# only for Fp with Fp2 = Fp[i]/(i^2 + 1), xi = 1 + i and sizeof(Fp) = 48
c5_fp2_tbl = [
	('fp2_addA_', '2_add', void3u),
	('fp2_subA_', '2_sub', void3u),
	('fp2_negA_', '2_neg', void2u),
	('fp2_mul2A_', '2_mul2', void2u),
	('fp2_mulA_', '2_mul', void3u),
	('fp2_sqrA_', '2_sqr', void2u),
	('fp2_mul_xiA_', '2_mul_xi', void2u),
]

def c5_name(pre, suf):
	return pre[:-1] + suf

def gen_c5_proto(pre, tbls):
	print(f'extern Unit {pre}p[];')
	for tbl in tbls:
		for (slot, suf, args) in tbl:
			print(f'void {c5_name(pre, suf)}({args});')

# set the slots of tbls to the functions with the prefix pre
def gen_c5_set(name, pre, tbls, setFpMul):
	print(f'static inline void {name}(Op& op)')
	print('{')
	for tbl in tbls:
		for (slot, suf, args) in tbl:
			print(f'	op.{slot} = {c5_name(pre, suf)};')
	if setFpMul:
		print('	op.fp_mul = fp::func_ptr_cast<void4u>(op.fp_mulA_); // used in toMont/fromMont')
	print('}')

print('#if defined(MCL_USE_LLVM) && !defined(MCL_WASM32)')
