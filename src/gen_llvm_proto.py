print('extern "C" {')
gen_c5_proto('mcl_c5_fp_', [c5_fp_tbl, c5_fpDbl_tbl, c5_fp2_tbl])
gen_c5_proto('mcl_c5_fr_', [c5_fp_tbl])
print('}')
print('// register them to op (the caller checks that op.p is the prime of the functions)')
gen_c5_set('set_llvm_c5_fp', 'mcl_c5_fp_', [c5_fp_tbl, c5_fpDbl_tbl], True)
print('// Fp2 of BLS12-381 : xi_a == 1, u == 1 and sizeof(Fp) == 48 (the offset of the second component is fixed)')
gen_c5_set('set_llvm_c5_fp2', 'mcl_c5_fp_', [c5_fp2_tbl], False)
gen_c5_set('set_llvm_c5_fr', 'mcl_c5_fr_', [c5_fp_tbl], True)
print('#endif')

