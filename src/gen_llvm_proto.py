import argparse
import primetbl

parser = argparse.ArgumentParser(description='generate src/llvm_proto.hpp')
parser.add_argument('-fpbit', type=int, default=384, help='MCL_FP_BIT given to src/gen.py (sizeof(Fp) of the Fp2 functions of the p-fixed code)')
opt = parser.parse_args()

N32tbl = [6, 7, 8, 12, 16]
N64tbl = [3, 4, 6, 8]

def gen_get_ptr(t):
	name = t[0]
	retType = t[1]
	ret = t[2]
	args = t[3]
	print(f'static inline {retType} get_llvm_{name}(size_t n)')
	print('{')
	print('#ifdef MCL_USE_LLVM')
	print('	switch (n) {')
	print('	default: return 0;')
	print('#if MCL_SIZEOF_UNIT == 4')
	for i in N32tbl:
		print(f'	case {i}: return mcl_{name}{i}L;')
	print('#else')
	for i in N64tbl:
		print(f'	case {i}: return mcl_{name}{i}L;')
	print('#endif')
	print('	}')
	print('''#else
	(void)n;
	return 0;
#endif
}''')

def gen_proto(t):
	name = t[0]
	retType = t[1]
	ret = t[2]
	args = t[3]
	for i in set(N32tbl+N64tbl):
		print(f'{ret} mcl_{name}{i}L({args});')

def gen_sqr_mont_impl(suf, n):
	print(f'static inline void mcl_fp_sqrMont{suf}{n}L(Unit *z, const Unit *x, const Unit *p) {{ return mcl_fp_mont{suf}{n}L(z, x, x, p); }}')

def gen_sqr_mont(suf):
	print('#ifdef MCL_USE_LLVM')
	print('#if MCL_SIZEOF_UNIT == 4')
	for i in N32tbl:
		gen_sqr_mont_impl(suf, i)
	print('#else')
	for i in N64tbl:
		gen_sqr_mont_impl(suf, i)
	print('#endif')
	print('#endif')

void3u = 'Unit*, const Unit*, const Unit*'
void4u = 'Unit*, const Unit*, const Unit*, const Unit*'

void3uType = 'bint::void_ppp'
void4uType = 'bint::void_pppp'
tbl = [
	('fp_add', void4uType, 'void', void4u),
	('fp_sub', void4uType, 'void', void4u),
	('fp_addNF', void4uType, 'void', void4u),
	('fp_subNF', void4uType, 'void', void4u),
	('fp_mont', void4uType, 'void', void4u),
	('fp_montNF', void4uType, 'void', void4u),
	('fp_montRed', void3uType, 'void', void3u),
	('fp_montRedNF', void3uType, 'void', void3u),
	('fpDbl_add', void4uType, 'void', void4u),
	('fpDbl_sub', void4uType, 'void', void4u),
]

# the MCL_FP_BIT of the generation of src/base{32,64}.ll (the -fpbit of
# src/gen.py = the MCL_FP_BIT of the Makefile): sizeof(Fp) of the Fp2
# functions of the p-fixed code. fp.cpp rejects a build with a different
# MCL_FP_BIT by #error (regenerate by make update_all_asm MCL_FP_BIT=... and make header).
print(f'#define MCL_FP_BIT_LLVM {opt.fpbit}')
print('namespace mcl { namespace fp {')

print('extern "C" {')
for t in tbl:
	gen_proto(t)
print('void mcl_fp_mulNIST_P192L(Unit *, const Unit *, const Unit *, const Unit *);')
print('void mcl_fp_sqr_NIST_P192L(Unit *, const Unit *, const Unit *);')
print('void mcl_fpDbl_mod_NIST_P192L(Unit *, const Unit *, const Unit *);')
print('void mcl_fpDbl_mod_NIST_P521L(Unit *, const Unit *, const Unit *);')
print('}')

gen_sqr_mont('')
gen_sqr_mont('NF')

tbl.append(('fp_sqrMont', void3uType, 'void', void3u))
tbl.append(('fp_sqrMontNF', void3uType, 'void', void3u))

for t in tbl:
	gen_get_ptr(t)

# p-fixed functions of the exported curves of src/primetbl.py (BN254: mcl_c0_*,
# BLS12-381: mcl_c5_*) generated by common.gen_fixed (src/gen.py): the same
# ABI as the Xbyak functions (no p argument), so they are registered to the A_
# slots of Op (see setLLVMFixedCode in fp.cpp).
# (slot of Op, suffix of the function name, C argument list)
# The function name is the prefix + the suffix; the prefixes are
# 'mcl_c5_fp_' (fixed_fp_tbl), 'mcl_c5_fpDbl_' (fixed_fpDbl_mod_tbl,
# fixed_fpDbl_tbl), 'mcl_c5_fp2_' (fixed_fp2_tbl) and 'mcl_c5_fp2Dbl_'
# (fixed_fp2Dbl_tbl).
void2u = 'Unit*, const Unit*'
fixed_fp_tbl = [
	('fp_addA_', 'add', void3u),
	('fp_subA_', 'sub', void3u),
	('fp_negA_', 'neg', void2u),
	('fp_mul2A_', 'mul2', void2u),
	('fp_mulA_', 'mul', void3u),
	('fp_sqrA_', 'sqr', void2u),
]
fixed_fpDbl_mod_tbl = [
	('fpDbl_modA_', 'mod', void2u),
]
# only for Fp (hasFp2 of gen_fixed)
fixed_fpDbl_tbl = [
	('fpDbl_addA_', 'add', void3u),
	('fpDbl_subA_', 'sub', void3u),
]
# only for Fp with Fp2 = Fp[i]/(i^2 + 1), xi = 1 + i and sizeof(Fp) = MCL_FP_BIT_LLVM / 8
fixed_fp2_tbl = [
	('fp2_addA_', 'add', void3u),
	('fp2_subA_', 'sub', void3u),
	('fp2_negA_', 'neg', void2u),
	('fp2_mul2A_', 'mul2', void2u),
	('fp2_mulA_', 'mul', void3u),
	('fp2_sqrA_', 'sqr', void2u),
	('fp2_mul_xiA_', 'mul_xi', void2u),
]
# Fp2Dbl (lazy reduction of Fp6/Fp12): b of Fp2Dbl at 2 sizeof(Fp)
fixed_fp2Dbl_tbl = [
	('fp2Dbl_mulPreA_', 'mulPre', void3u),
	('fp2Dbl_sqrPreA_', 'sqrPre', void2u),
	('fp2Dbl_mul_xiA_', 'mul_xi', void2u),
]

# tbls : list of (prefix, table)
def gen_fixed_proto(tbls):
	for (pre, tbl) in tbls:
		for (slot, suf, args) in tbl:
			print(f'void {pre}{suf}({args});')

# set the slots of tbls to the functions with their prefixes
def gen_fixed_set(name, tbls, setFpMul):
	print(f'static inline void {name}(Op& op)')
	print('{')
	for (pre, tbl) in tbls:
		for (slot, suf, args) in tbl:
			print(f'	op.{slot} = {pre}{suf};')
	if setFpMul:
		print('	op.fp_mul = fp::func_ptr_cast<void4u>(op.fp_mulA_); // used in toMont/fromMont')
	print('}')

print('#if defined(MCL_USE_LLVM) && !defined(MCL_WASM32)')
print('// p-fixed functions (see common.gen_fixed in src/gen.py); the Xbyak ABI (no p argument)')
for cv in primetbl.exportedCurves():
	hasFp2 = cv.u == 1 and cv.xi_a == 1 # Fp2 = Fp[i]/(i^2 + 1) and xi = 1 + i (gen_fixed)
	preFp = f'mcl_c{cv.c}_fp_'
	preFr = f'mcl_c{cv.c}_fr_'
	preFpDbl = preFp[:-1] + 'Dbl_'
	preFp2 = preFp[:-1] + '2_'
	preFp2Dbl = preFp[:-1] + '2Dbl_'
	preFrDbl = preFr[:-1] + 'Dbl_'
	fpTbls = [(preFp, fixed_fp_tbl), (preFpDbl, fixed_fpDbl_mod_tbl + (fixed_fpDbl_tbl if hasFp2 else []))]
	fp2Tbls = [(preFp2, fixed_fp2_tbl), (preFp2Dbl, fixed_fp2Dbl_tbl)] if hasFp2 else []
	frTbls = [(preFr, fixed_fp_tbl), (preFrDbl, fixed_fpDbl_mod_tbl)] if cv.r else []
	print(f'// {cv.name} (curve type {cv.c} of include/mcl/curve_type.h)')
	print('extern "C" {')
	print(f'extern Unit {preFp}p[];')
	gen_fixed_proto(fpTbls + fp2Tbls)
	if frTbls:
		print(f'extern Unit {preFr}p[];')
		gen_fixed_proto(frTbls)
	print('}')
	print('// register them to op (the caller checks that op.p is the prime of the functions)')
	gen_fixed_set(f'set_llvm_c{cv.c}_fp', fpTbls, True)
	if hasFp2:
		print('// Fp2 = Fp[i]/(i^2 + 1) with xi = 1 + i and sizeof(Fp) == MCL_FP_BIT_LLVM / 8 (the caller checks u == 1, xi_a == 1 and op.maxN)')
		gen_fixed_set(f'set_llvm_c{cv.c}_fp2', fp2Tbls, False)
	if frTbls:
		gen_fixed_set(f'set_llvm_c{cv.c}_fr', frTbls, True)
print('#endif')

print('}}')
